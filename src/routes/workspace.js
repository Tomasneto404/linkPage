const router=require('express').Router();
const {requireAuth,requireAdmin,requireLoginIfPrivate,requirePublicAuth}=require('../middleware/auth');
const {wrapAsync}=require('../middleware/error');
const c=require('../controllers/workspaceController');
const multer=require('multer');
const crypto=require('node:crypto');
const backupService=require('../services/backupService');
const uploadBackup=multer({storage:multer.diskStorage({destination:(req,file,done)=>done(null,backupService.directory()),filename:(req,file,done)=>done(null,`.import-${crypto.randomUUID()}`)}),limits:{fileSize:512*1024*1024,files:1}}).single('backup');
const handle=fn=>wrapAsync(async(req,res)=>{try{return await fn(req,res);}catch(error){if(error.status===400)return res.status(400).json({error:error.message});throw error;}});
router.get('/api/workspace/search',requireLoginIfPrivate,requirePublicAuth,handle(c.search));
router.get('/api/workspace/filters',requireAuth,handle(c.filters));
router.post('/api/workspace/filters',requireAuth,handle(c.saveFilter));
router.delete('/api/workspace/filters/:id',requireAuth,handle(c.deleteFilter));
router.get('/api/workspace/library',requireAdmin,handle(c.library));
router.get('/api/workspace/managed-groups',requireAuth,handle(c.managedGroups));
router.put('/api/workspace/managed-groups/:id',requireAuth,c.requireManager,handle(c.updateManagedGroup));
router.post('/api/workspace/managed-groups/:id/members',requireAuth,c.requireManager,handle(c.grantMember));
router.delete('/api/workspace/managed-groups/:id/members/:userId',requireAuth,c.requireManager,handle(c.revokeMember));
router.put('/api/workspace/links/:id',requireAdmin,handle(c.updateLink));
router.put('/api/workspace/groups/:id',requireAdmin,handle(c.updateGroup));
router.get('/api/workspace/versions',requireAdmin,handle(c.versions));
router.get('/api/workspace/versions/:id',requireAdmin,handle(c.version));
router.post('/api/workspace/versions/:id/restore',requireAdmin,handle(c.restoreVersion));
router.get('/api/workspace/notifications',requireAdmin,handle(c.notifications));
router.post('/api/workspace/notifications/read',requireAdmin,handle(c.readNotification));
router.get('/api/workspace/presets',requireAdmin,handle(c.presets));
router.post('/api/workspace/presets',requireAdmin,handle(c.savePreset));
router.get('/api/workspace/presets/:id',requireAdmin,handle(c.preset));
router.post('/api/workspace/presets/:id/apply',requireAdmin,handle(c.preset));
router.delete('/api/workspace/presets/:id',requireAdmin,handle(c.preset));
router.get('/api/workspace/backups',requireAdmin,handle(c.backupList));
router.put('/api/workspace/backups/schedule',requireAdmin,handle(c.backupSettings));
router.post('/api/workspace/backups',requireAdmin,handle(c.createBackup));
router.post('/api/workspace/backups/import',requireAdmin,(req,res,next)=>backupService.isBusy()?res.status(409).json({error:'A backup is already in progress'}):next(),uploadBackup,handle(c.importBackup));
router.get('/api/workspace/backups/:id/file',requireAdmin,handle(c.backupFile));
router.post('/api/workspace/backups/:id/restore',requireAdmin,handle(c.restoreBackup));
router.delete('/api/workspace/backups/:id',requireAdmin,handle(c.backupFile));
module.exports=router;
