/** The small SQL dialect used by the existing models, on PostgreSQL. Values
 * remain bound parameters throughout; they are never interpolated into SQL. */
const now = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";
function statements(sql) {
  const out=[]; let start=0, quote=false, comment=false;
  for(let i=0;i<sql.length;i++) {
    if(comment){if(sql[i]==='\n')comment=false;continue;}
    if(!quote && sql.slice(i,i+2)==='--'){comment=true;i++;continue;}
    if(sql[i]==="'"){if(quote&&sql[i+1]==="'"){i++;continue;}quote=!quote;}
    if(!quote&&sql[i]===';'){out.push(sql.slice(start,i));start=i+1;}
  }
  out.push(sql.slice(start));return out.map(s=>s.replace(/^\s*(?:--[^\n]*\n\s*)*/,'').trim()).filter(Boolean);
}
function translate(input) {
  let sql=input.trim().replace(/;$/,'');
  const pragma=sql.match(/^PRAGMA\s+table_info\((\w+)\)$/i);
  if(pragma)return {sql:'SELECT column_name AS name, data_type AS type, ordinal_position-1 AS cid FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=$1 ORDER BY ordinal_position',params:[pragma[1]]};
  sql=sql.replace(/\bINTEGER\s+PRIMARY KEY\s+AUTOINCREMENT\b/gi,'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi,'BIGINT')
    .replace(/\bDATETIME\b(?!\s*\()/gi,'TEXT')
    .replace(/strftime\('%Y-%m-%dT%H:%M:%fZ',\s*'now'\)/gi,`to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`)
    .replace(/datetime\('now',\s*(\?|'[^']*')\)/gi,(_,interval)=>`to_char((now() AT TIME ZONE 'UTC') + (${interval}::interval), 'YYYY-MM-DD HH24:MI:SS')`)
    .replace(/datetime\('now'\)/gi,now)
    .replace(/datetime\((COALESCE\([^)]*\))\)/gi,'$1')
    .replace(/\bdate\((\w+)\)/gi,'left($1,10)')
    .replace(/\bIS NOT\s+\?/gi,'IS DISTINCT FROM ?')
    .replace(/\bIS\s+\?/gi,'IS NOT DISTINCT FROM ?')
    .replace(/\bMIN\((\?,\s*absolute_expires_at)\)/gi,'LEAST($1)')
    .replace(/\bMAX\((0\s*,[^)]*)\)/gi,'GREATEST($1)')
    .replace(/\bCURRENT_TIMESTAMP\b/gi,now)
    .replace(/\bsqlite_master\b/gi,"(SELECT table_name AS name, 'table' AS type FROM information_schema.tables WHERE table_schema=current_schema() UNION ALL SELECT indexname AS name,'index' AS type FROM pg_indexes WHERE schemaname=current_schema()) AS sqlite_master");
  if(/^INSERT OR REPLACE\b/i.test(sql)) {
    const match=sql.match(/^INSERT OR REPLACE INTO\s+(\w+)\s*\(([^)]+)\)/i);
    const key={settings:'key',workspace_link_details:'link_id',workspace_group_details:'group_id'}[match?.[1]];
    if(!key)throw new Error('Unsupported upsert table');
    const columns=match[2].split(',').map(s=>s.trim());
    sql=sql.replace(/^INSERT OR REPLACE/i,'INSERT')+` ON CONFLICT (${key}) DO UPDATE SET `+columns.filter(c=>c!==key).map(c=>`${c}=EXCLUDED.${c}`).join(',');
  } else if(/^INSERT OR IGNORE\b/i.test(sql))sql=sql.replace(/^INSERT OR IGNORE/i,'INSERT')+' ON CONFLICT DO NOTHING';
  // PostgreSQL requires non-aggregate columns to be grouped explicitly.
  sql=sql.replace(/GROUP BY c\.link_id\b/gi,'GROUP BY l.id').replace(/GROUP BY c\.ip_address\b/gi,'GROUP BY c.ip_address, tg.tag');
  let n=0,quoted=false,out='';
  for(let i=0;i<sql.length;i++) {
    const c=sql[i];if(c==="'"){out+=c;if(quoted&&sql[i+1]==="'"){out+=sql[++i];continue;}quoted=!quoted;continue;}
    out+=c==='?'&&!quoted?'$'+(++n):c;
  }
  return {sql:out};
}
module.exports={translate,statements};
